import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import tensorflow as tf

from tensorflow.keras.datasets import imdb
from tensorflow.keras.preprocessing.sequence import pad_sequences
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Embedding, LSTM, Dense, Dropout
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score,
    f1_score, confusion_matrix, ConfusionMatrixDisplay
)

print("TensorFlow version:", tf.__version__)
print("Setup completed successfully!")

vocab_size = 10000
max_length = 200

(x_train, y_train), (x_test, y_test) = imdb.load_data(
    num_words=vocab_size
)

print("Training samples:", len(x_train))
print("Testing samples:", len(x_test))
print("First review sequence:", x_train[0][:20])
print("First sentiment label:", y_train[0])


x_train = pad_sequences(
    x_train, maxlen=max_length, padding="post", truncating="post"
)

x_test = pad_sequences(
    x_test, maxlen=max_length, padding="post", truncating="post"
)


x_val = x_train[-5000:]
y_val = y_train[-5000:]

x_train = x_train[:-5000]
y_train = y_train[:-5000]

print("Final training shape:", x_train.shape)
print("Validation shape:", x_val.shape)
print("Testing shape:", x_test.shape)
print("Dataset preparation completed!")

model = Sequential([
    Embedding(input_dim=vocab_size, output_dim=64),
    LSTM(64),
    Dropout(0.5),
    Dense(1, activation="sigmoid")
])

model.compile(
    optimizer="adam",
    loss="binary_crossentropy",
    metrics=["accuracy"]
)

model.build(input_shape=(None, max_length))
model.summary()

history = model.fit(
    x_train,
    y_train,
    epochs=5,
    batch_size=64,
    validation_data=(x_val, y_val),
    verbose=1
)

print("Model training completed!")

test_loss, test_accuracy = model.evaluate(x_test, y_test, verbose=1)

y_prob = model.predict(x_test, verbose=0)
y_pred = (y_prob >= 0.5).astype(int).flatten()

accuracy = accuracy_score(y_test, y_pred)
precision = precision_score(y_test, y_pred, zero_division=0)
recall = recall_score(y_test, y_pred, zero_division=0)
f1 = f1_score(y_test, y_pred, zero_division=0)

print("\nTEST PERFORMANCE")
print("Test Loss:", round(test_loss, 4))
print("Accuracy:", round(accuracy, 4))
print("Precision:", round(precision, 4))
print("Recall:", round(recall, 4))
print("F1 Score:", round(f1, 4))

# Accuracy graph
plt.figure(figsize=(8, 5))
plt.plot(history.history["accuracy"], label="Training Accuracy")
plt.plot(history.history["val_accuracy"], label="Validation Accuracy")
plt.title("Accuracy vs Epoch")
plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.legend()
plt.grid(True)
plt.show()

# Loss graph
plt.figure(figsize=(8, 5))
plt.plot(history.history["loss"], label="Training Loss")
plt.plot(history.history["val_loss"], label="Validation Loss")
plt.title("Loss vs Epoch")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()
plt.grid(True)
plt.show()

cm = confusion_matrix(y_test, y_pred)

display = ConfusionMatrixDisplay(
    confusion_matrix=cm,
    display_labels=["Negative", "Positive"]
)

display.plot()
plt.title("LSTM Sentiment Analysis Confusion Matrix")
plt.show()

word_index = imdb.get_word_index()

def predict_sentiment(review):
    words = review.lower().split()
    sequence = []

    for word in words:
        index = word_index.get(word, 2) + 3 if word in word_index else 2
        if index >= vocab_size:
            index = 2
        sequence.append(index)

    padded = pad_sequences(
        [sequence], maxlen=max_length,
        padding="post", truncating="post"
    )

    probability = model.predict(padded, verbose=0)[0][0]
    sentiment = "Positive" if probability >= 0.5 else "Negative"

    print("Review:", review)
    print("Predicted sentiment:", sentiment)
    print("Positive probability:", round(float(probability), 4))
    print()

reviews = [
    "This movie was fantastic and I enjoyed every moment",
    "The film was boring and a complete waste of time",
    "The acting was wonderful and the story was excellent",
    "I hated this movie because it was very disappointing"
]

for review in reviews:
    predict_sentiment(review)